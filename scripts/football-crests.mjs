// Turns the approved crest step files (Football shared/mockups/crests/*.svg) into src/football/art/crestSteps.ts.
// Usage: node scripts/football-crests.mjs "<path to mockups/crests>"
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
const dir = process.argv[2];
if (!dir) throw new Error('pass the crests folder');
const out = {};
for (const f of readdirSync(dir).filter((f) => /^[1-5][a-e]\.svg$/.test(f)).sort()) {
  const s = readFileSync(join(dir, f), 'utf8');
  // Drop the <svg>, the <style> and the night background; keep the drawing.
  const body = s.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<style>[\s\S]*?<\/style>/, '').replace(/<rect width="100" height="100" fill="#0b1022"\/>/, '');
  out[f.slice(0, 2)] = body;
}
if (Object.keys(out).length !== 25) throw new Error(`expected 25 crests, got ${Object.keys(out).length}`);
const ts = `// Generated by scripts/football-crests.mjs from the approved crest steps. Do not edit by hand.\nexport const CREST_STEPS: Record<string, string> = ${JSON.stringify(out, null, 2)};\n`;
writeFileSync('src/football/art/crestSteps.ts', ts);
console.log('wrote 25 crest steps');
